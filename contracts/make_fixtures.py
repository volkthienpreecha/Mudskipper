def write_png(path, width, height, rgba_rows):
    raw = b"".join(b"\x00" + bytes(row) for row in rgba_rows)
    def chunk(tag, data):
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
    png = (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0))
           + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))
    path.write_bytes(png)


def hex_rgb(h):
    return int(h[1:3], 16), int(h[3:5], 16), int(h[5:7], 16)


def render_overlay(path, tile, features, obs_by_field_pass, pass_):
    size = 1000
    minx, miny, maxx, maxy = tile["bbox"]
    canvas = [bytearray(size * 4) for _ in range(size)]
    band = stripe_band(pass_, tile["id"], (min(f["properties"]["lon"] for f in features),
                                           max(f["properties"]["lon"] for f in features)))
    for f in features:
        o = obs_by_field_pass[(f["properties"]["field_id"], pass_["pass_id"])]["observed"]
        ring = f["geometry"]["coordinates"][0]
        xs = [pt[0] for pt in ring]
        ys = [pt[1] for pt in ring]
        c0 = int((min(xs) - minx) / (maxx - minx) * size)
        c1 = int((max(xs) - minx) / (maxx - minx) * size)
        r0 = int((maxy - max(ys)) / (maxy - miny) * size)
        r1 = int((maxy - min(ys)) / (maxy - miny) * size)
        if "ps_db" in o:  # Freeman-Durden composite: R = double bounce, G = volume, B = surface
            comps = [lin(o["pd_db"]), lin(o["pv_db"]), lin(o["ps_db"])]
        else:
            comps = [lin(o["hh_db"]), lin(o["hv_db"]) * 3, lin(o["hh_db"]) * 0.6]
        top = max(comps)
        rgb = [int(40 + 215 * (cv / top) ** 0.5) for cv in comps]
        for r in range(max(r0, 0), min(r1 + 1, size)):
            row = canvas[r]
            for cpx in range(max(c0, 0), min(c1 + 1, size)):
                lon = minx + (cpx + 0.5) / size * (maxx - minx)
                if band and band[0] <= lon < band[1]:
                    continue  # no data in the gap stripe
                row[cpx * 4:cpx * 4 + 4] = bytes((rgb[0], rgb[1], rgb[2], 235))
    write_png(path, size, size, canvas)


def render_hist(path, stage, observations):
    width, height = 600, 300
    bg, silt, reed = hex_rgb("#0E1A1F"), hex_rgb("#2C3E46"), hex_rgb("#9FB0A8")
    water, mud = hex_rgb("#3FA7D6"), hex_rgb("#C98B4E")
    lo, hi, nbins = -24.0, 0.0, 48
    counts = {"flooded": [0] * nbins, "drained": [0] * nbins}
    for o in observations:
        if o["stage"] == stage and o["inferred"]["state"] in counts:
            b = int((o["observed"]["hh_db"] - lo) / (hi - lo) * nbins)
            if 0 <= b < nbins:
                counts[o["inferred"]["state"]][b] += 1
    peak = max(max(counts["flooded"]), max(counts["drained"]), 1)
    pad_l, pad_b, pad_t = 20, 24, 16
    plot_h = height - pad_b - pad_t
    bw = (width - 2 * pad_l) / nbins
    rows = [bytearray(bytes((*bg, 255)) * width) for _ in range(height)]

    def blend(r, c, color, alpha):
        px = rows[r][c * 4:c * 4 + 3]
        rows[r][c * 4:c * 4 + 3] = bytes(int(px[i] * (1 - alpha) + color[i] * alpha) for i in range(3))

    for state, color in (("drained", mud), ("flooded", water)):
        for b, cnt in enumerate(counts[state]):
            h = int(plot_h * cnt / peak)
            for r in range(height - pad_b - h, height - pad_b):
                for cpx in range(int(pad_l + b * bw) + 1, int(pad_l + (b + 1) * bw)):
                    blend(r, cpx, color, 0.7)
    for cpx in range(pad_l, width - pad_l):
        blend(height - pad_b, cpx, silt, 1.0)
    for k in range(0, nbins + 1, 8):  # tick every 4 dB
        cpx = min(int(pad_l + k * bw), width - pad_l - 1)
        for r in range(height - pad_b, height - pad_b + 6):
            blend(r, cpx, reed, 1.0)
    write_png(path, width, height, rows)


# ------------------------------------------------------------------------------------------------ writers
def dump(obj):
    return json.dumps(obj, ensure_ascii=False, indent=2, allow_nan=False) + "\n"


def dump_collection(head, features):
    """GeoJSON with one feature per line: small files, readable diffs."""
    lines = ",\n".join(json.dumps(f, ensure_ascii=False, separators=(",", ":"), allow_nan=False) for f in features)
    head_s = json.dumps(head, ensure_ascii=False, separators=(",", ":"))[:-1]
    return head_s + ',"features":[\n' + lines + "\n]}\n"


def dump_states(obj):
    """states.json: header and id lists compact, one field per line in `states`."""
    head = {k: v for k, v in obj.items() if k != "states"}
    s = json.dumps(head, ensure_ascii=False, separators=(",", ":"), allow_nan=False)[:-1]
    rows = ",\n".join(json.dumps(x) for x in obj["states"])
    return s + ',"states":[\n' + rows + "\n]}\n"


def dump_jsonl(rows):
    return "".join(json.dumps(r, ensure_ascii=False, separators=(",", ":"), allow_nan=False) + "\n" for r in rows)


def sha256_file(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def hdr():
    return {"v": 1, "run_id": RUN_ID, "fixture": True}


