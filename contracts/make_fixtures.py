def build_claims(features, tiles):
    rng = rules.Mulberry32(rules.derive(SEED, "claims"))
    pool = list(features)
    for i in range(len(pool) - 1, 0, -1):  # seeded shuffle
        j = int(rng() * (i + 1))
        pool[i], pool[j] = pool[j], pool[i]
    chosen = pool[:53]
    claims = []

    def claimed():
        r = rng()
        return ["awd"] if r < 0.5 else (["dsr"] if r < 0.7 else ["awd", "dsr"])

    for f in chosen:
        props = f["properties"]
        r = rng()
        geom = f["geometry"] if r < 1 / 3 else {"type": "Point", "coordinates": [props["lon"], props["lat"]]}
        p = {"claim_id": "", "claimed": claimed(), "synthetic": True}
        if rng() < 0.5:
            p["field_id"] = props["field_id"]
        claims.append({"type": "Feature", "geometry": geom, "properties": p})
    dup = chosen[0]["properties"]  # second claim on the same field: exercises candidate merging
    claims.append({"type": "Feature", "geometry": {"type": "Point", "coordinates": [dup["lon"], dup["lat"]]},
                   "properties": {"claim_id": "", "claimed": ["dsr"], "synthetic": True}})
    for i in range(6):  # points outside every mapped field
        t = tiles[i % 2]
        minx, miny, maxx, maxy = t["bbox"]
        lon = round(minx + (0.05 + 0.15 * rng()) * (maxx - minx), 7)
        lat = round(miny + (0.05 + 0.15 * rng()) * (maxy - miny), 7)
        p = {"claim_id": "", "claimed": claimed(), "synthetic": True}
        if i % 2 == 0:
            p["area_ha"] = round(1 + rng() * 3, 2)
        claims.append({"type": "Feature", "geometry": {"type": "Point", "coordinates": [lon, lat]}, "properties": p})
    for i in range(len(claims) - 1, 0, -1):
        j = int(rng() * (i + 1))
        claims[i], claims[j] = claims[j], claims[i]
    for i, c in enumerate(claims, start=1):
        c["properties"] = {"claim_id": f"SYN-{i:04d}", **{k: v for k, v in c["properties"].items() if k != "claim_id"}}
    assert len(claims) == 60
    return claims


