def db(x):
    return 10 * math.log10(x)


def lin(x):
    return 10 ** (x / 10)


def stripe_band(pass_, tile, cluster):
    """Quad-pol gap stripe: a lon band whose position shifts from pass to pass (SPEC A11)."""
    if pass_["pol_mode"] != "QP":
        return None
    u = rules.Mulberry32(rules.derive(SEED, "stripe:" + pass_["pass_id"] + ":" + tile))()
    lo, hi = cluster
    start = lo + u * (hi - lo)
    return start, start + 0.0045


def build_observations(features, passes):
    used = [p for p in passes if p["used"]]
    clusters = {}
    for t in TILES:
        lons = [f["properties"]["lon"] for f in features if f["properties"]["tile"] == t["id"]]
        clusters[t["id"]] = (min(lons), max(lons))
    lines, truth_kinds = [], {}
    for f in features:
        props = f["properties"]
        fid = props["field_id"]
        kind, drained = truth_model(fid)
        truth_kinds[fid] = kind
        rng = rules.Mulberry32(rules.derive(SEED, "obs:" + fid))
        for p in used:
            stage = rules.stage_of(p["datetime"], STAGES)
            x = rules.days(p["datetime"])
            truth = "drained" if drained(x) else "flooded"
            acc = PARAMS["per_pass_accuracy"][stage]
            label = truth if rng() < acc else ("flooded" if truth == "drained" else "drained")
            ambiguous = rng() < (0.5 if kind == "noisy" else 0.1)
            if ambiguous:
                p_fl = 0.36 + rng() * 0.28
            elif label == "flooded":
                p_fl = 0.66 + rng() * 0.335
            else:
                p_fl = 0.005 + rng() * 0.335
            p_fl = round(p_fl, 4)
            n_px = max(1, round(props["area_ha"] * 10000 / (p["pixel_m"] ** 2)))
            band = stripe_band(p, props["tile"], clusters[props["tile"]])
            flags = []
            if band and band[0] <= props["lon"] < band[1]:
                valid = 0.15 + rng() * 0.40
                flags.append("gap_stripe")
            else:
                valid = 0.88 + rng() * 0.12
            valid = round(valid, 3)
            if valid < rules.VALID_FRAC_MIN:
                flags.append("low_valid_frac")
            if n_px < 10:
                flags.append("few_pixels")
            if p["pol_mode"] == "DH":
                flags.append("dual_pol_only")
            hh_f, hv_f, fd_f = MEANS[(stage, "flooded")]
            hh_d, hv_d, fd_d = MEANS[(stage, "drained")]
            hh = round(hh_d + p_fl * (hh_f - hh_d) + gauss(rng, 0, 0.8), 2)
            hv = round(hv_d + p_fl * (hv_f - hv_d) + gauss(rng, 0, 0.8), 2)
            observed = {"hh_db": hh, "hv_db": hv}
            if p["pol_mode"] == "QP":
                vv = round(hh - 1.0 + gauss(rng, 0, 0.6), 2)
                span = lin(hh) + 2 * lin(hv) + lin(vv)
                fr = [max(0.01, d + p_fl * (fl - d) + gauss(rng, 0, 0.03)) for d, fl in zip(fd_d, fd_f)]
                tot = sum(fr)
                ps, pd, pv = (round(db(span * v / tot), 2) for v in fr)
                observed.update({"vv_db": vv, "ps_db": ps, "pd_db": pd, "pv_db": pv})
            observed["hh_hv_db"] = round(hh - hv, 2)
            method = "fd_gmm_v1" if p["pol_mode"] == "QP" else "hhhv_v1"
            lines.append({"v": 1, "run_id": RUN_ID, "fixture": True, "field_id": fid, "pass_id": p["pass_id"],
                          "n_px": n_px, "valid_frac": valid, "observed": observed, "stage": stage,
                          "inferred": {"state": rules.state_from(p_fl, valid), "p_flooded": p_fl,
                                       "confidence": round(rules.confidence_from(p_fl), 4), "method": method},
                          "flags": flags})
    return lines, truth_kinds


