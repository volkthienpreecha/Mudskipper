# ------------------------------------------------------------------------------------------------ geometry helpers
def m_per_deg(lat):
    phi = math.radians(lat)
    m_lat = 111132.954 - 559.822 * math.cos(2 * phi) + 1.175 * math.cos(4 * phi)
    m_lon = 111412.84 * math.cos(phi) - 93.5 * math.cos(3 * phi) + 0.118 * math.cos(5 * phi)
    return m_lon, m_lat


def tile_bbox(center):
    m_lon, m_lat = m_per_deg(center[1])
    dlon, dlat = HALF_SIDE_M / m_lon, HALF_SIDE_M / m_lat
    return [round(center[0] - dlon, 4), round(center[1] - dlat, 4), round(center[0] + dlon, 4), round(center[1] + dlat, 4)]


def ring_area_ha(ring, lat0):
    m_lon, m_lat = m_per_deg(lat0)
    s = 0.0
    for (x1, y1), (x2, y2) in zip(ring, ring[1:]):
        s += (x1 * m_lon) * (y2 * m_lat) - (x2 * m_lon) * (y1 * m_lat)
    return abs(s) / 2 / 10000


def gauss(rng, mu=0.0, sigma=1.0):
    u1 = max(rng(), 1e-12)
    return mu + sigma * math.sqrt(-2 * math.log(u1)) * math.cos(2 * math.pi * rng())


