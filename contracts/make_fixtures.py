def build_fields(tile):
    """Rectangular fields in 300 m blocks split into strips: the killa/murabba look of Punjab farmland."""
    rng = rules.Mulberry32(rules.derive(SEED, "fields:" + tile["id"]))
    cx, cy = tile["center"]
    m_lon, m_lat = m_per_deg(cy)
    block, road, bund = 300.0, 12.0, 4.0
    origin_x, origin_y = -1250.0 + rng() * 300, -1250.0 + rng() * 300
    features, n, row = [], 0, 0
    while n < FIELDS_PER_TILE:
        for col in range(8):
            if n >= FIELDS_PER_TILE:
                break
            if rng() < 0.08:  # village, orchard or canal block
                continue
            strips = 2 + int(rng() * 4)  # 2..5
            ns = rng() < 0.5
            x0 = origin_x + col * (block + road)
            y0 = origin_y + row * (block + road)
            for s in range(strips):
                if n >= FIELDS_PER_TILE:
                    break
                w = block / strips
                if ns:
                    xa, xb, ya, yb = x0 + s * w + bund, x0 + (s + 1) * w - bund, y0 + bund, y0 + block - bund
                else:
                    xa, xb, ya, yb = x0 + bund, x0 + block - bund, y0 + s * w + bund, y0 + (s + 1) * w - bund
                to_ll = lambda x, y: [round(cx + x / m_lon, 7), round(cy + y / m_lat, 7)]
                ring = [to_ll(xa, ya), to_ll(xb, ya), to_ll(xb, yb), to_ll(xa, yb), to_ll(xa, ya)]
                n += 1
                lon = round((ring[0][0] + ring[2][0]) / 2, 7)
                lat = round((ring[0][1] + ring[2][1]) / 2, 7)
                features.append({"type": "Feature",
                                 "geometry": {"type": "Polygon", "coordinates": [ring]},
                                 "properties": {"field_id": f"{tile['id']}-{n:05d}", "tile": tile["id"],
                                                "district": tile["district"],
                                                "area_ha": round(ring_area_ha(ring, lat), 4), "source": "ftw",
                                                "rice_mask_frac": round(0.55 + rng() * 0.45, 2),
                                                "lon": lon, "lat": lat}})
        row += 1
    return features


