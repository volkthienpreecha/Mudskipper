def truth_model(field_id):
    """A field's hidden water history: a function day -> drained? Never written to disk."""
    rng = rules.Mulberry32(rules.derive(SEED, "truth:" + field_id))
    r = rng()
    t_lo, t_hi = rules.days("2026-06-10"), rules.days("2026-07-02")
    T = t_lo + rng() * (t_hi - t_lo)
    cyc = 4 + rng() * 6
    frac = 0.3 + rng() * 0.2
    phi = rng() * cyc
    if r < 0.36:
        kind = "awd"

        def drained(x):
            if x < T:
                return True
            if x < T + 14:
                return False
            if x < T + 85:
                y = (x - T - 14 + phi) / cyc
                return (y - math.floor(y)) >= 1 - frac
            return True
    elif r < 0.72:
        kind = "cf"
        single = rng() < 0.51
        dur = 3 + rng() * 3
        s = T + 20 + rng() * 50

        def drained(x):
            if x < T or x >= T + 95:
                return True
            return single and s <= x < s + dur
    elif r < 0.88:
        kind = "dsr"
        first_irrigation = rules.days("2026-07-12") + rng() * 13

        def drained(x):
            if x < first_irrigation or x >= rules.days("2026-09-30"):
                return True
            y = (x - first_irrigation + phi) / cyc
            return (y - math.floor(y)) >= 1 - frac
    elif r < 0.96:
        kind = "late"
        T2 = rules.days("2026-07-16") + rng() * 12

        def drained(x):
            return x < T2 or x >= T2 + 90
    else:
        kind = "noisy"

        def drained(x):
            return rng() < 0.5
    return kind, drained


