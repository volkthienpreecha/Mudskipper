def png_pixels(data: bytes):
    """Decoded IDAT bytes, so a different zlib build that compresses differently still compares equal."""
    i, idat, header = 8, b"", b""
    while i < len(data):
        n = struct.unpack(">I", data[i:i + 4])[0]
        tag, body = data[i + 4:i + 8], data[i + 8:i + 8 + n]
        if tag == b"IHDR":
            header = body
        elif tag == b"IDAT":
            idat += body
        i += 12 + n
    return header, zlib.decompress(idat)


def compare_trees(expected: pathlib.Path, actual: pathlib.Path) -> list[str]:
    rel = lambda root: {p.relative_to(root).as_posix() for p in root.rglob("*") if p.is_file()}
    a, b = rel(expected), rel(actual)
    problems = [f"only in committed fixtures: {x}" for x in sorted(a - b)]
    problems += [f"only in fresh build: {x}" for x in sorted(b - a)]
    for name in sorted(a & b):
        x, y = (expected / name).read_bytes(), (actual / name).read_bytes()
        if x == y:
            continue
        if name.endswith(".png") and x.startswith(b"\x89PNG") and y.startswith(b"\x89PNG") and png_pixels(x) == png_pixels(y):
            continue
        problems.append(f"differs: {name}")
    return problems


def check(out: pathlib.Path) -> int:
    with tempfile.TemporaryDirectory(prefix="mudskipper-fixtures-") as tmp:
        fresh = pathlib.Path(tmp) / "fixtures"
        build(fresh)
        problems = compare_trees(out, fresh)
    if problems:
        print("fixtures-check: committed fixtures differ from a fresh build (run `make fixtures` and commit):")
        for p in problems:
            print("  " + p)
        return 1
    print(f"fixtures-check: {out} matches a fresh build byte for byte")
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", default=str(pathlib.Path(__file__).resolve().parent / "fixtures"))
    ap.add_argument("--check", action="store_true", help="rebuild in a temp dir and compare with --out")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args(argv)
    out = pathlib.Path(args.out).resolve()
    if args.check:
        sys.exit(check(out))
    if out.exists() and any(out.iterdir()):
        readme = out / "README.md"
        if not (readme.exists() and MARKER in readme.read_text(encoding="utf-8")):
            sys.exit(f"refusing to overwrite {out}: it is not empty and was not written by this script")
    out.parent.mkdir(parents=True, exist_ok=True)
    tmp = pathlib.Path(tempfile.mkdtemp(prefix=".fixtures-", dir=out.parent))
    try:
        summary = build(tmp)
        if out.exists():
            shutil.rmtree(out)
        os.replace(tmp, out)
    finally:
        if tmp.exists():
            shutil.rmtree(tmp)
    if not args.quiet:
        print(f"fixtures written to {out}")
        for k, v in summary.items():
            print(f"  {k}: {v}")


if __name__ == "__main__":
    main()
