#!/usr/bin/env node
/**
 * Compile the API JSON Schemas (contracts/schemas) into a standalone, dependency-free validator module for
 * the tests that run inside workerd (test/gen/validators.js): every API response schema, checked with the
 * real JSON Schemas rather than a hand-written copy.
 *
 *   node scripts/gen-validators.ts          # write test/gen/validators.js
 *   node scripts/gen-validators.ts --check  # fail if the file in the repo is stale (CI)
 *
 * Why generated: Ajv compiles schemas with `new Function`, which workerd forbids. Ajv's standalone mode emits
 * the compiled code instead; its two runtime helpers are inlined so the output imports nothing. The output is
 * deterministic, so it lives in the repo and is checked for drift like the fixtures. (Production validates
 * the audit request with core's dependency-free `validateAuditRequest`.)
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import standaloneModule from "ajv/dist/standalone/index.js";
import { createSchemaAjv } from "./lib/schemas.ts";

type Standalone = (ajv: unknown, refs: Record<string, string>) => string;
const standaloneCode: Standalone =
  (standaloneModule as unknown as { default?: Standalone }).default ?? (standaloneModule as unknown as Standalone);

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

/** Export name → schema path (relative to contracts/schemas). */
export const RESPONSE_VALIDATORS: Record<string, string> = {
  auditRequest: "api/audit_request.schema.json",
  auditResponse: "api/audit_response.schema.json",
  checks: "api/checks.schema.json",
  detectability: "api/detectability.schema.json",
  error: "api/error.schema.json",
  fieldDetail: "api/field_detail.schema.json",
  fieldsPage: "api/fields_page.schema.json",
  health: "api/health.schema.json",
  meta: "api/meta.schema.json",
  passes: "api/passes.schema.json",
  provenance: "api/provenance.schema.json",
  states: "api/states.schema.json",
  story: "api/story.schema.json",
  live: "live.schema.json",
};

const TARGETS: { file: string; validators: Record<string, string> }[] = [
  { file: join(root, "test", "gen", "validators.js"), validators: RESPONSE_VALIDATORS },
];

/** Ajv's runtime helpers, inlined (same semantics as ajv/dist/runtime/{equal,ucs2length}). */
const HELPERS: Record<string, string> = {
  "ajv/dist/runtime/equal": `(function equal(a, b) {
  if (a === b) return true;
  if (a && b && typeof a === "object" && typeof b === "object") {
    if (Array.isArray(a)) {
      if (!Array.isArray(b) || a.length !== b.length) return false;
      for (let i = 0; i < a.length; i++) if (!equal(a[i], b[i])) return false;
      return true;
    }
    if (Array.isArray(b)) return false;
    const ka = Object.keys(a);
    if (ka.length !== Object.keys(b).length) return false;
    for (const k of ka) if (!Object.prototype.hasOwnProperty.call(b, k) || !equal(a[k], b[k])) return false;
    return true;
  }
  return a !== a && b !== b;
})`,
  "ajv/dist/runtime/ucs2length": `(function ucs2length(str) {
  let length = 0, pos = 0;
  const len = str.length;
  while (pos < len) {
    length++;
    const value = str.charCodeAt(pos++);
    if (value >= 0xd800 && value <= 0xdbff && pos < len) {
      const next = str.charCodeAt(pos);
      if ((next & 0xfc00) === 0xdc00) pos++;
    }
  }
  return length;
})`,
};

function generate(validators: Record<string, string>): string {
  const { ajv, base } = createSchemaAjv({ code: { source: true, esm: true, lines: false } });
  const refs = Object.fromEntries(Object.entries(validators).map(([name, rel]) => [name, base + rel]));
  let code = standaloneCode(ajv, refs);
  code = code.replace(/require\("([^"]+)"\)\.default/g, (_m, mod: string) => {
    const helper = HELPERS[mod];
    if (!helper) throw new Error(`generated code needs an unknown Ajv runtime helper: ${mod}`);
    return helper;
  });
  if (/require\(/.test(code)) throw new Error("generated validator still contains require()");
  return (
    "// GENERATED by platform/scripts/gen-validators.ts from contracts/schemas. Do not edit: run `npm run gen -w platform`.\n" +
    "// @ts-nocheck\n" +
    code +
    "\n"
  );
}

let stale = 0;
for (const { file, validators } of TARGETS) {
  const code = generate(validators);
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(file, "utf8");
    } catch {
      /* missing counts as stale */
    }
    if (current !== code) {
      console.error(`${file} is stale: run \`npm run gen -w platform\` and commit the result.`);
      stale++;
    }
  } else {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, code);
    console.log(`wrote ${file} (${code.length} bytes)`);
  }
}
if (stale) process.exit(1);
if (process.argv.includes("--check")) console.log("generated validators are up to date");
